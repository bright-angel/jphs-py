"""Extract constant tables from the upstream jphs / IJG sources.

Run from the repository root:  python tools/gen_tables.py
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "upstream"
JPEG = UPSTREAM / "jpeg-8a"
OUT = ROOT / "src" / "jphs" / "_tables.py"


def _body(path: pathlib.Path, anchor: str) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    start = text.index(anchor)
    start = text.index("{", start) + 1
    end = text.index("};", start)
    return text[start:end]


def blowfish_key() -> list[int]:
    body = _body(UPSTREAM / "bf.c", "const Blowfish_Key Blowfish_Init_Key = {")
    words = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", body)]
    if len(words) != 1042:
        raise SystemExit(f"expected 1042 Blowfish words, got {len(words)}")
    return words


def ltab() -> list[int]:
    body = _body(UPSTREAM / "ltable.h", "int ltab[771] = {")
    values = [int(x) for x in re.findall(r"-?\d+", body)]
    if len(values) != 771:
        raise SystemExit(f"expected 771 ltab entries, got {len(values)}")
    return values


def natural_order() -> list[int]:
    body = _body(JPEG / "jutils.c", "const int jpeg_natural_order[DCTSIZE2+16] = {")
    values = [int(x) for x in re.findall(r"-?\d+", body)]
    if len(values) != 80:
        raise SystemExit(f"expected 80 natural-order entries, got {len(values)}")
    return values


def emit(name: str, values: list[int], fmt: str = "0x{:08x}") -> str:
    lines = [f"{name} = ("]
    per_line = 6 if fmt.startswith("0x") else 10
    for i in range(0, len(values), per_line):
        chunk = ", ".join(fmt.format(v) for v in values[i : i + per_line])
        lines.append(f"    {chunk},")
    lines.append(")")
    return "\n".join(lines)


def main() -> None:
    text = (
        '"""Generated by tools/gen_tables.py from the upstream sources."""\n\n'
        + emit("BLOWFISH_INIT_KEY", blowfish_key())
        + "\n\n"
        + emit("LTAB", ltab(), "{}")
        + "\n\n"
        + emit("NATURAL_ORDER", natural_order(), "{}")
        + "\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
